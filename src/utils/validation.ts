import { z } from 'zod'

/**
 * Схема валидации формы обратной связи с помощью Zod
 * Обеспечивает строгую проверку данных на клиенте
 * 
 * UX-решение: Валидация в реальном времени с понятными сообщениями
 * снижает фрустрацию пользователя и улучшает конверсию
 */
export const contactSchema = z.object({
  name: z
    .string()
    .min(2, 'Имя должно содержать минимум 2 символа')
    .max(50, 'Имя не может превышать 50 символов')
    .regex(/^[а-яА-Яa-zA-Z\s-]+$/, 'Имя может содержать только буквы, пробелы и дефис'),
  
  phone: z
    .string()
    .min(10, 'Введите корректный номер телефона')
    .regex(/^[\d\s+()-]+$/, 'Введите корректный номер телефона'),
  
  email: z
    .string()
    .email('Введите корректный email адрес')
    .min(5, 'Email слишком короткий'),
  
  message: z
    .string()
    .min(10, 'Опишите вашу проблему кратко (минимум 10 символов)')
    .max(1000, 'Сообщение не может превышать 1000 символов'),
  
  consent: z
    .boolean()
    .refine(val => val === true, 'Необходимо дать согласие на обработку персональных данных'),
})

export type ContactSchema = z.infer<typeof contactSchema>
